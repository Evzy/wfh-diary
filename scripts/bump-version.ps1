# Bumps version.json (versionCode + patch versionName), then syncs API + Android.
# Called automatically by .githooks/pre-commit. Skip with: SKIP_VERSION_BUMP=1 git commit ...
param(
    [switch]$SyncOnly
)

$ErrorActionPreference = "Stop"
$repoRoot = Split-Path -Parent $PSScriptRoot
$versionFile = Join-Path $repoRoot "version.json"

function Write-Utf8NoBom([string]$Path, [string]$Content) {
    $utf8 = New-Object System.Text.UTF8Encoding $false
    [System.IO.File]::WriteAllText($Path, $Content, $utf8)
}

if (-not (Test-Path $versionFile)) {
    Write-Error "Missing version.json at repo root."
}

$json = Get-Content $versionFile -Raw | ConvertFrom-Json
$versionCode = [int]$json.versionCode
$versionName = [string]$json.versionName

if (-not $SyncOnly) {
    $versionCode += 1
    if ($versionName -match '^(\d+)\.(\d+)\.(\d+)$') {
        $patch = [int]$Matches[3] + 1
        $versionName = "{0}.{1}.{2}" -f $Matches[1], $Matches[2], $patch
    }
    else {
        $versionName = "$versionName.$versionCode"
    }

    $versionJson = (@{ versionName = $versionName; versionCode = $versionCode } | ConvertTo-Json -Compress)
    Write-Utf8NoBom $versionFile $versionJson

    Write-Host "Bumped to $versionName ($versionCode)"
}

# --- Sync API ---
$appVersionCs = @"
// Generated by scripts/bump-version.ps1 — do not edit by hand.
namespace WfhDiary.Api;

public static class AppVersion
{
    public const string VersionName = "$versionName";
    public const int VersionCode = $versionCode;
}
"@
$appVersionPath = Join-Path $repoRoot "services/api/WfhDiary.Api/AppVersion.cs"
Write-Utf8NoBom $appVersionPath $appVersionCs

$csprojPath = Join-Path $repoRoot "services/api/WfhDiary.Api/WfhDiary.Api.csproj"
$csproj = Get-Content $csprojPath -Raw
$csproj = $csproj -replace '<Version>[^<]*</Version>', "<Version>$versionName</Version>"
if ($csproj -notmatch '<Version>') {
    $csproj = $csproj -replace '(<PropertyGroup>)', "`$1`r`n    <Version>$versionName</Version>"
}
Write-Utf8NoBom $csprojPath $csproj

Write-Host "Synced API -> $versionName"
